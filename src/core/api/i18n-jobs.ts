export function valueLabel(name: string, fallback?: string): string {
  if (/_NR$/i.test(name) && !/_(FG|BMW)_NR$/i.test(name)) return `${valueLabel(name.replace(/_NR$/i, ''), fallback)} (code)`;
  const base = baseOf(name);
  if (VALUES[base]) return VALUES[base];
  if (base.endsWith('_ADC') && VALUES[base.slice(0, -4)]) return `${VALUES[base.slice(0, -4)]} (sensor voltage)`;
  if (fallback) return fallback;
  const words = base.split('_').filter(Boolean).map((t) => TOKENS[t] ?? t.charAt(0) + t.slice(1).toLowerCase());
  const s = translate(words.join(' ')).replace(/\s+/g, ' ').trim();
  return s.charAt(0).toUpperCase() + s.slice(1);
}

export function jobLabel(comment: string): string {
  const c = comment.trim();
  if (!c) return '';
  return JOBS[c] ?? translate(c.replace(/\s+/g, ' ').replace(/ auslesen$| lesen$/i, ''));
}

export function argLabel(comment: string): string {
  const c = comment.trim();
  return ARGS[c] ?? translate(c);
}
