/** Strips the SGBD result decorations: STAT_/STATUS_ prefix, _WERT/_EIN/_TEXT suffix, data block marker. */
function baseOf(name: string) {
  return name
    .toUpperCase()
    .replace(/^(STATUS|STAT|LESEN)_/, '')
    .replace(/_(WERT|EIN|TEXT|STAT|NR)$/, '')
    .replace(/_MWB$/, '')
    .replace(/_MWB_/, '_');
}

