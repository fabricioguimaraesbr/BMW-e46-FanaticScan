// Troubleshooting guides for E46 faults: what a fault means, the likely causes on this car, how to check them with
// the values this app reads, how to fix them and what to do afterwards.
// Written for this app from general E46 workshop knowledge. Nothing here is taken from BMW's ISTA/TIS documents;
// the only BMW strings are the module fault texts the guides are matched against.

export interface GuideCheck {
  text: string;
  /** value bases to watch in Live Data (see baseKey) */
  live?: string[];
  /** a procedure on the Service screen (task id) */
  service?: string;
}

export interface FaultGuide {
  id: string;
  title: string;
  /** module short names the guide applies to; empty = any module */
  modules: string[];
  /** matched against the English fault text, the German original and the OBD P-code */
  match: RegExp;
  meaning: string;
  causes: string[];
  checks: GuideCheck[];
  fix: string[];
  after?: string[];
  /** shown in red at the top */
  warning?: string;
  /** a generic guide by fault type, used when no specific one fits */
  generic?: boolean;
}

