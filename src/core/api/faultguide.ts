export interface FaultLike {
  text: string;
  textOriginal: string;
  label?: string;
  pcode?: string;
  details: string[];
  present: boolean | null;
  frequency: number | null;
}

/** The best guide for a fault of a module: a specific one when the text matches, otherwise one by fault type. */
export function guideFor(module: string, f: FaultLike): FaultGuide {
  const hay = [f.text, f.textOriginal, f.label ?? '', f.pcode ?? ''].join(' | ');
  const fits = (g: FaultGuide) => (!g.modules.length || g.modules.includes(module)) && g.match.test(hay);
  return FAULT_GUIDES.find((g) => !g.generic && fits(g)) ?? FAULT_GUIDES.find((g) => g.generic && fits(g))!;
}

/** Notes from the fault's own type and status (open circuit, short, sporadic…). */
export function faultTypeNotes(f: FaultLike): string[] {
  const t = [...f.details, f.text].join(' ').toLowerCase();
  const n: string[] = [];
  if (f.present === false) n.push('Not present right now: the fault happened earlier and went away. Look for loose connectors and wiring that moves (wiggle test while watching Live Data), then clear it and see whether it comes back.');
  if (f.present === true) n.push('Present now: the condition is still there, so it can be measured right away.');
  if (f.frequency !== null && f.frequency > 5) n.push(`Seen ${f.frequency} times: a recurring problem rather than a one-off glitch.`);
  if (/short (circuit )?to ground|kurzschluss nach masse/.test(t)) n.push('Short to ground: look for a wire rubbing through its insulation against the body or engine.');
  if (/short (circuit )?to (b\+|battery|plus|ubatt)|kurzschluss nach plus/.test(t)) n.push('Short to battery voltage: look for a damaged harness touching a powered wire, or water in a connector.');
  if (/open circuit|line break|unterbrechung|leitungsunterbrechung/.test(t)) n.push('Open circuit: check the connector first (pins pushed back, corrosion), then the wire and the component itself.');
  if (/sporadic|sporadisch|intermittent/.test(t)) n.push('Sporadic: the signal dropped out briefly. Connectors and wiring that move with the engine or doors are the usual suspects.');
  if (/too high|zu hoch|above/.test(t)) n.push('Value too high: compare with the live value and the normal range.');
  if (/too low|zu niedrig|below/.test(t)) n.push('Value too low: compare with the live value and the normal range.');
  return n;
}

/** Readable names for the values the guides point to (value bases). */
