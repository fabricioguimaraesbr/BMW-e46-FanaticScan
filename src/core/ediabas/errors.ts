export function errorDescription(code: number): string {
  if (DESCRIPTIONS[code]) return DESCRIPTIONS[code];
  if (code >= 250 && code <= 349) return `RUN-${String(code - 250).padStart(4, '0')}`;
  return `ERROR ${code}`;
}

/** Thrown when EDIABAS raises an error (equivalent to EdiabasNetException). */
export class EdiabasError extends Error {
  readonly code: number;
  constructor(code: number, message?: string) {
    super(message ?? errorDescription(code));
    this.code = code;
    this.name = 'EdiabasError';
  }
}

